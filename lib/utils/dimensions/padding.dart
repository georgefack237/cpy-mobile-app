
import 'package:flutter/material.dart';

class AppPadding{

  double padH16(Size size){
    return size.width * .045;
  }

  double padV15(Size size){
    return size.width * .045;
  }

  double padV30(Size size){
    return size.width * .060;
  }

  double padH8(Size size){
    return size.width * .015;
  }

}